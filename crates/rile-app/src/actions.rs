const FILE_LIST: &str = "FileList";
const WORKSPACE: &str = "Workspace";

/// Single source of truth for keyboard shortcuts. `mod` is cmd on macOS and
/// ctrl elsewhere.
pub fn bind_keys(cx: &mut App) {
    // Bindings need 'static keystroke strings; these are built once at startup.
    let k = |keys: &str| -> &'static str {
        let m = if cfg!(target_os = "macos") { "cmd" } else { "ctrl" };
        Box::leak(keys.replace("mod", m).into_boxed_str())
    };

    cx.bind_keys([
        KeyBinding::new(k("mod-q"), Quit, None),
        KeyBinding::new(k("mod-["), GoBack, Some(WORKSPACE)),
        KeyBinding::new("backspace", GoBack, Some(FILE_LIST)),
        KeyBinding::new(k("mod-]"), GoForward, Some(WORKSPACE)),
        KeyBinding::new(k("mod-up"), GoUp, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-h"), GoHome, Some(WORKSPACE)),
        KeyBinding::new(k("mod-l"), EditPath, Some(WORKSPACE)),
        KeyBinding::new(k("mod-r"), Refresh, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-."), ToggleHidden, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-t"), ToggleTheme, Some(WORKSPACE)),
        KeyBinding::new(k("mod-,"), OpenSettings, Some(WORKSPACE)),
        KeyBinding::new(k("mod-c"), Copy, Some(FILE_LIST)),
        KeyBinding::new(k("mod-x"), Cut, Some(FILE_LIST)),
        KeyBinding::new(k("mod-v"), Paste, Some(FILE_LIST)),
        KeyBinding::new(k("mod-backspace"), MoveToTrash, Some(FILE_LIST)),
        KeyBinding::new("delete", MoveToTrash, Some(FILE_LIST)),
        KeyBinding::new(k("mod-shift-backspace"), DeletePermanently, Some(FILE_LIST)),
        KeyBinding::new("shift-delete", DeletePermanently, Some(FILE_LIST)),
        KeyBinding::new("f2", Rename, Some(FILE_LIST)),
        KeyBinding::new(k("mod-shift-n"), NewFolder, Some(FILE_LIST)),
        KeyBinding::new(k("mod-alt-n"), NewFile, Some(FILE_LIST)),
        KeyBinding::new(k("mod-d"), Duplicate, Some(FILE_LIST)),
        KeyBinding::new(k("mod-a"), SelectAll, Some(FILE_LIST)),
        KeyBinding::new("escape", ClearSelection, Some(FILE_LIST)),
        KeyBinding::new("down", SelectNext, Some(FILE_LIST)),
        KeyBinding::new("up", SelectPrev, Some(FILE_LIST)),
        KeyBinding::new("shift-down", ExtendNext, Some(FILE_LIST)),
        KeyBinding::new("shift-up", ExtendPrev, Some(FILE_LIST)),
        KeyBinding::new("home", SelectFirst, Some(FILE_LIST)),
        KeyBinding::new("end", SelectLast, Some(FILE_LIST)),
        KeyBinding::new("enter", OpenSelected, Some(FILE_LIST)),
        KeyBinding::new(k("mod-down"), OpenSelected, Some(FILE_LIST)),
        KeyBinding::new(k("mod-o"), OpenSelected, Some(FILE_LIST)),
        // ⌘T opens a tab (as in Finder); favorites move to ⌃⌘T ("Add to Sidebar").
        KeyBinding::new(if cfg!(target_os = "macos") { "cmd-ctrl-t" } else { "ctrl-alt-t" }, ToggleFavorite, Some(FILE_LIST)),
        KeyBinding::new(k("mod-t"), NewTab, Some(WORKSPACE)),
        KeyBinding::new(k("mod-w"), CloseTab, Some(WORKSPACE)),
        KeyBinding::new("ctrl-tab", NextTab, Some(WORKSPACE)),
        KeyBinding::new("ctrl-shift-tab", PrevTab, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-]"), NextTab, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-["), PrevTab, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-s"), ToggleSidebar, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-o"), OpenInNewTab, Some(FILE_LIST)),
        KeyBinding::new("left", SelectLeft, Some(FILE_LIST)),
        KeyBinding::new("right", SelectRight, Some(FILE_LIST)),
        KeyBinding::new("space", ToggleQuickLook, Some(FILE_LIST)),
        KeyBinding::new(k("mod-y"), ToggleQuickLook, Some(FILE_LIST)),
        KeyBinding::new(k("mod-i"), ShowProperties, Some(FILE_LIST)),
        KeyBinding::new(k("mod-alt-c"), CopyPath, Some(FILE_LIST)),
        KeyBinding::new(k("mod-alt-o"), OpenInOtherPane, Some(FILE_LIST)),
        KeyBinding::new("f5", CopyToOtherPane, Some(FILE_LIST)),
        KeyBinding::new("f6", MoveToOtherPane, Some(FILE_LIST)),
        KeyBinding::new("tab", SwitchPane, Some(FILE_LIST)),
        KeyBinding::new(k("mod-f"), FocusSearch, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-f"), AdvancedSearch, Some(WORKSPACE)),
        KeyBinding::new(k("mod-1"), ViewList, Some(WORKSPACE)),
        KeyBinding::new(k("mod-2"), ViewGrid, Some(WORKSPACE)),
        KeyBinding::new(k("mod-3"), ViewColumns, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-d"), ToggleDualPane, Some(WORKSPACE)),
        KeyBinding::new(k("mod-f1"), SelectLeftDrive, Some(WORKSPACE)),
        KeyBinding::new(k("mod-f2"), SelectRightDrive, Some(WORKSPACE)),
        KeyBinding::new(k("mod-shift-p"), TogglePreviewPanel, Some(WORKSPACE)),
        KeyBinding::new(k("mod-k"), AiAsk, Some(WORKSPACE)),
        KeyBinding::new(k("mod-/"), ShowShortcuts, Some(WORKSPACE)),
        // Registered last so they win over the plain FileList bindings while previewing.
        KeyBinding::new("escape", ClosePreview, Some("FileList && previewing")),
        KeyBinding::new("space", ClosePreview, Some("FileList && previewing")),
    ]);
}
